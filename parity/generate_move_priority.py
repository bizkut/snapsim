#!/usr/bin/env python3
"""Generate move_priority.rs from the 59.15.1 IL2CPP initializer and class dump.

Usage: python3 parity/generate_move_priority.py LIBIL2CPP CUBEDEF_CS > crates/snapsim/src/move_priority.rs
Requires an ARM64-capable objdump. The input files are not distributed with this repo.
"""
import re
import subprocess
import sys
from pathlib import Path

if len(sys.argv) != 3:
    raise SystemExit(__doc__)
asm = subprocess.check_output([
    "objdump", "-d", "--start-address=0x7c9deb0", "--stop-address=0x7c9e4d8", sys.argv[1]
], text=True)
dump = Path(sys.argv[2]).read_text()

def ids(class_name):
    body = dump.split(f"    class {class_name} :", 1)[1].split("        class Id\n", 1)[1].split("\n        }", 1)[0]
    return {int(offset, 16): name for offset, name in re.findall(
        rf"static /\*0x([0-9a-f]+)\*/ CubeDef.Id<CubeDef.{class_name}> (\w+);", body)}

def extract(start, end, names, expected):
    block = asm.split(start + ":", 1)[1].split(end + ":", 1)[0]
    entries = []
    priority = offset = None
    for line in block.splitlines():
        p = re.search(r"mov\s+w2, #0x([0-9a-f]+)", line)
        k = re.search(r"ldr\s+x1, \[x8, #0x([0-9a-f]+)\]", line)
        if p:
            priority = int(p[1], 16)
        if k:
            offset = int(k[1], 16)
        if re.search(r"bl\s+0x6413d4c\b", line):
            if priority is None or offset not in names:
                raise ValueError(f"unresolved dictionary entry: {line}")
            entries.append((names[offset], priority))
            priority = offset = None
    if len(entries) != expected or len({name for name, _ in entries}) != expected:
        raise ValueError(f"expected {expected} unique entries, got {entries}")
    return entries

cards = extract("7c9e020", "7c9e30c", ids("CardDef"), 27)
locations = extract("7c9e380", "7c9e3b0", ids("LocationDef"), 2)
print('''//! Generated by parity/generate_move_priority.py from client 59.15.1.
//! MoveSystem::.cctor 0x7c9deb0; GetSourcePriority 0x7c9e67c.
//! Ability sources use the ability definition owner's CardDef/LocationDef/FactionDef ID;
//! entity sources use ability-text CardDef ID, LocationDef ID, or FactionDef ID.
//! Augments are CardDef IDs. The faction dictionary is empty. Unknown keys use i32::MAX.
''')
for name, entries in (("card", cards), ("location", locations)):
    print(f'pub(crate) fn {name}_priority(id: &str) -> i32 {{\n    match id {{')
    for key, value in entries:
        print(f'        "{key}" => {value},')
    print('        _ => i32::MAX,\n    }\n}', end='\n\n' if name == "card" else '\n')
